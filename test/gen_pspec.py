#!/usr/bin/env python3
"""Generate data/languages/pic16f153xx.pspec (and the global/nohighptr ranges of the cspec) from
the special function register summary of DS40001865D (PIC16(L)F15325/45, table 4-10).

  gen_pspec.py <ds.txt> <languages dir>

The pspec holds: the PCLATH value assumed for code at each 256-word page (CODE offsets in a pspec count bytes) (the usual convention
that PCLATH names the page the code lives in), the volatile ranges (every implemented SFR), the
register groups, the default symbols (Reset, Interrupt and every SFR by its data sheet name) and
the data memory block. The symbol names and pcHi are what Ghidra's analysis of real firmware relies on."""
import re, sys
ds = open(sys.argv[1], errors='replace').read().split('\n')
outd = sys.argv[2]
reg = {}
for i in range(2440, 3560):
    m = re.match(r'^\s*([0-9A-F]{3,4})h\s+([A-Za-z][A-Za-z0-9_]*)(?:\(\d\))?\s', ds[i])
    if m:
        reg[int(m.group(1), 16)] = m.group(2)
assert len(reg) > 250, len(reg)

x = ['<?xml version="1.0" encoding="UTF-8"?>', '',
     '<!-- Generated by test/gen_pspec.py from DS40001865D (PIC16(L)F15325/45); do not edit by hand. -->',
     '<processor_spec>',
     '  <programcounter register="PC"/>',
     '  <data_space space="DATA"/>',
     '  <context_data>',
     '    <context_set space="CODE">',
     '      <set name="doPseudo" val="0"/>',
     '    </context_set>',
     '    <tracked_set space="CODE">',
     '      <set name="BSR" val="0"/>',
     '    </tracked_set>']
# pcHi (= PCLATH<6:3>) starts at the page number of each 2K-word page; CODE offsets in a pspec count
# bytes, so a page is 0x1000 long
for page in range(16):
    x += ['    <context_set space="CODE" first="0x%04x" last="0x%04x">' % (page * 0x1000, page * 0x1000 + 0xfff),
          '      <set name="pcHi" val="%d"/>' % page, '    </context_set>']
x += ['  </context_data>',
      '  <volatile outputop="write_sfr" inputop="read_sfr">']
# contiguous runs of implemented SFRs
addrs = sorted(reg)
runs = []
for a in addrs:
    if runs and a == runs[-1][1] + 1:
        runs[-1][1] = a
    else:
        runs.append([a, a])
for lo, hi in runs:
    x.append('    <range space="DATA" first="0x%04x" last="0x%04x"/>' % (lo, hi))
x += ['  </volatile>',
      '  <register_data>',
      '    <register name="STATUS" group="STATUS"/>',
      '    <register name="PC" group="PC"/>',
      '    <register name="PCL" group="PC"/>',
      '    <register name="PCLATH" group="PC"/>',
      '  </register_data>',
      '  <default_symbols>',
      '    <symbol name="Reset" address="CODE:0000" entry="true"/>',
      '    <symbol name="Interrupt" address="CODE:0004" entry="true"/>']
for a in addrs:
    x.append('    <symbol name="%s" address="DATA:%04x" entry="false"/>' % (reg[a], a))
x += ['  </default_symbols>',
      '  <default_memory_blocks>',
      '    <memory_block name="GPR" start_address="DATA:0000" mode="rw" length="0x2000" initialized="false"/>',
      '  </default_memory_blocks>',
      '</processor_spec>', '']
open(outd + '/pic16f153xx.pspec', 'w').write('\n'.join(x))

# cspec ranges: GPR = 0x20-0x6F of banks 0..49 (linear data memory ends at 0x2FEF = 50 banks of 80
# bytes) and the common RAM; nohighptr = core registers and SFRs
g = ['    <range space="CODE" first="0x0000" last="0xffff"/>']
for b in range(50):
    g.append('    <range space="DATA" first="0x%04x" last="0x%04x"/>' % (b * 0x80 + 0x20, b * 0x80 + 0x6f))
g.append('    <range space="DATA" first="0x0070" last="0x007f"/>')
n = []
for b in range(64):
    lo = b * 0x80
    hi = lo + (0x1f if b < 50 else 0x7f)
    n.append('    <range space="DATA" first="0x%04x" last="0x%04x"/>' % (lo, hi))
cs = open(outd + '/pic16f153xx.cspec').read()
cs = re.sub(r'(<global>\n).*?(\s*</global>)', lambda m: m.group(1) + '\n'.join(g) + m.group(2), cs, flags=re.S)
cs = re.sub(r'(<nohighptr>\n).*?(\s*</nohighptr>)', lambda m: m.group(1) + '\n'.join(n) + m.group(2), cs, flags=re.S)
open(outd + '/pic16f153xx.cspec', 'w').write(cs)
