#!/usr/bin/env python3
"""Build test/real/algos.asm with gpasm and write emulator cases for it (PicEmuTest format).
The program runs CRC-16, a 16x16 multiply, XTEA, a bubble sort and a hex-digit table on inputs
set by the case; the expected results are computed here from the algorithms' definitions.

  algos.py <outdir>      writes <outdir>/algos.hex, algos.lst and <outdir>/algos-cases.txt
"""
import os, random, re, subprocess, sys

here = os.path.dirname(os.path.abspath(__file__))
out = sys.argv[1]
os.makedirs(out, exist_ok=True)
subprocess.run(['gpasm', '-o', out + '/algos.hex', os.path.join(here, 'algos.asm')], check=True,
               capture_output=True)
lst = open(out + '/algos.lst').read()
done = int(re.search(r'^done\s+ADDRESS\s+([0-9A-Fa-f]+)', open(out + '/algos.lst').read(), re.M).group(1), 16) \
    if re.search(r'^done\s+ADDRESS', lst, re.M) else None
words = {}
for l in open(out + '/algos.hex'):
    l = l.strip()
    if l.startswith(':') and l[7:9] == '00':
        n, a = int(l[1:3], 16), int(l[3:7], 16)
        d = bytes.fromhex(l[9:9 + 2 * n])
        for i in range(0, n, 2):
            words[(a + i) // 2] = d[i] | d[i + 1] << 8
if done is None:
    done = int(re.search(r'^(\w+)?\s*([0-9A-F]{4})\s+\S+\s+\d+\s+done:', lst, re.M).group(2), 16)
lo = 0x100
code = [words.get(i, 0) for i in range(lo, max(words) + 1)]

def crc16(data):
    crc = 0xffff
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xffff if crc & 0x8000 else (crc << 1) & 0xffff
    return crc

def xtea(v0, v1, key):
    s, delta, m = 0, 0x9e3779b9, 0xffffffff
    for _ in range(32):
        v0 = (v0 + ((((v1 << 4) ^ (v1 >> 5)) + v1) ^ (s + key[s & 3]))) & m
        s = (s + delta) & m
        v1 = (v1 + ((((v0 << 4) ^ (v0 >> 5)) + v0) ^ (s + key[(s >> 11) & 3]))) & m
    return v0, v1

def chunks(addr, data):
    """set/expect lines for bytes at DATA:addr (at most 8 bytes per line, little endian)"""
    res = []
    for i in range(0, len(data), 8):
        part = data[i:i + 8]
        res.append(('DATA:%x/%d' % (addr + i, len(part)), int.from_bytes(bytes(part), 'little')))
    return res

rnd = random.Random(20261027)
vectors = [
    ('random1', [rnd.randrange(256) for _ in range(16)], rnd.randrange(65536), rnd.randrange(65536),
     rnd.randrange(1 << 32), rnd.randrange(1 << 32), [rnd.randrange(1 << 32) for _ in range(4)], 11),
    ('random2', [rnd.randrange(256) for _ in range(16)], rnd.randrange(65536), rnd.randrange(65536),
     rnd.randrange(1 << 32), rnd.randrange(1 << 32), [rnd.randrange(1 << 32) for _ in range(4)], 0),
    ('allones', [0xff] * 16, 0xffff, 0xffff, 0xffffffff, 0xffffffff, [0xffffffff] * 4, 15),
    ('zeros', [0] * 16, 0, 0, 0, 0, [0] * 4, 9),
    ('sorted_and_dups', [3, 3, 1, 1, 2, 2, 0, 0, 255, 255, 128, 127, 5, 5, 5, 5], 1, 65535, 1, 2, [1, 2, 3, 4], 10),
    ('descending', list(range(240, 0, -15)), 0x8000, 2, 0x80000000, 0x7fffffff, [5, 6, 7, 8], 12),
]
with open(out + '/algos-cases.txt', 'w') as f:
    f.write('# generated by test/real/algos.py; do not edit\n')
    for name, buf, a, b, v0, v1, key, nib in vectors:
        f.write('case algos_%s\ncode %s\nend %x\nsteps 400000\n' % (name, ' '.join('%04x' % w for w in code), done))
        sets = chunks(0x50, buf) + chunks(0x60, a.to_bytes(2, 'little')) + chunks(0x64, b.to_bytes(2, 'little'))
        sets += chunks(0x20, v0.to_bytes(4, 'little') + v1.to_bytes(4, 'little'))
        sets += chunks(0x28, b''.join(k.to_bytes(4, 'little') for k in key))
        sets += [('DATA:78', nib)]
        for k, v in sets:
            f.write('set %s 0x%x\n' % (k, v))
        e0, e1 = xtea(v0, v1, key)
        crc = crc16(buf)
        exp = [('DATA:70', crc >> 8), ('DATA:71', crc & 0xff), ('DATA:66/4', a * b)]
        exp += chunks(0x20, e0.to_bytes(4, 'little') + e1.to_bytes(4, 'little'))
        exp += chunks(0x50, sorted(buf))
        exp += [('DATA:78', ord('0123456789ABCDEF'[nib]))]
        for k, v in exp:
            f.write('expect %s 0x%x\n' % (k, v))
        f.write('end\n')
print('code words', len(code), 'done at 0x%x' % done, 'cases', len(vectors))
